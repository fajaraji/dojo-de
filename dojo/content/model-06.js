const BRIDGE = `with pesanan as (
  select o.order_id,
         date_trunc('month', o.order_ts)::date as bulan,
         o.status,
         o.shipping_fee,
         i.nilai_bersih,
         p.uang_masuk
  from app.orders as o
  join (
    select order_id, sum(qty * unit_price - discount) as nilai_bersih
    from app.order_items
    group by order_id
  ) as i on i.order_id = o.order_id
  left join (
    select order_id, sum(amount) as uang_masuk
    from app.payments
    where status = 'success'
    group by order_id
  ) as p on p.order_id = o.order_id
),
per_bulan as (
  select bulan,
         sum(shipping_fee) filter (where uang_masuk is not null) as ongkir,
         -sum(nilai_bersih) filter (where status = 'cancelled') as batal,
         coalesce(-sum(nilai_bersih) filter (where status <> 'cancelled' and uang_masuk is null), 0) as belum_dibayar
  from pesanan
  group by bulan
),
geser as (
  select bulan, sum(nilai) as beda_bulan_bayar
  from (
    select date_trunc('month', pa.paid_ts)::date as bulan, pa.amount as nilai
    from app.payments as pa
    where pa.status = 'success'
    union all
    select date_trunc('month', o.order_ts)::date, -pa.amount
    from app.payments as pa
    join app.orders as o on o.order_id = pa.order_id
    where pa.status = 'success'
  ) as x
  group by bulan
)
select m.year, m.month,
       f.gross_sales - m.net_amount as selisih,
       b.ongkir, b.batal, b.belum_dibayar, g.beda_bulan_bayar,
       f.gross_sales - m.net_amount - b.ongkir - b.batal - b.belum_dibayar - g.beda_bulan_bayar as belum_terjelaskan
from mart.sales_monthly as m
join raw.finance_monthly as f
  on extract(year from f.bln) = m.year and extract(month from f.bln) = m.month
join per_bulan as b on b.bulan = f.bln
join geser as g on g.bulan = f.bln
order by m.year, m.month;`;

