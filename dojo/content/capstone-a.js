/* ---------------------------------------------------------------- langkah 6: rekonsiliasi */
// Pemecahan penyebab sama dengan bab rekonsiliasi (ongkir, batal, belum dibayar, beda bulan bayar),
// tetapi dihitung dari tabel gudang data buatan peserta, dan disimpan sebagai view supaya bisa dibaca ulang.
const RECON = `create view dq.rekonsiliasi_finance as
with pesanan as (
  select f.order_id, d.year, d.month, o.status, o.shipping_fee,
         sum(f.net_amount) as nilai_bersih
  from dw.fact_order_line as f
  join dw.dim_date as d on d.date_key = f.order_date_key
  join stg.orders as o on o.order_id = f.order_id
  group by f.order_id, d.year, d.month, o.status, o.shipping_fee
),
bayar as (
  select p.order_id, d.year, d.month, p.amount
  from dw.fact_payment as p
  join dw.dim_date as d on d.date_key = p.paid_date_key
  where p.status = 'success'
),
dibayar as (
  select distinct order_id
  from bayar
),
per_bulan as (
  select pe.year, pe.month,
         coalesce(sum(pe.shipping_fee) filter (where db.order_id is not null), 0) as ongkir,
         coalesce(-sum(pe.nilai_bersih) filter (where pe.status = 'cancelled'), 0) as batal,
         coalesce(-sum(pe.nilai_bersih) filter (where pe.status <> 'cancelled' and db.order_id is null), 0) as belum_dibayar
  from pesanan as pe
  left join dibayar as db on db.order_id = pe.order_id
  group by pe.year, pe.month
),
geser as (
  select year, month, sum(nilai) as beda_bulan_bayar
  from (select year, month, amount as nilai
        from bayar
        union all
        select pe.year, pe.month, -b.amount
        from bayar as b
        join pesanan as pe on pe.order_id = b.order_id) as x
  group by year, month
)
select m.year, m.month,
       m.net_amount as mart_net_amount,
       f.gross_sales as finance_gross_sales,
       f.gross_sales - m.net_amount as selisih,
       b.ongkir, b.batal, b.belum_dibayar,
       coalesce(g.beda_bulan_bayar, 0) as beda_bulan_bayar,
       f.gross_sales - m.net_amount - b.ongkir - b.batal - b.belum_dibayar
         - coalesce(g.beda_bulan_bayar, 0) as belum_terjelaskan
from mart.sales_monthly as m
join raw.finance_monthly as f
  on extract(year from f.bln) = m.year and extract(month from f.bln) = m.month
join per_bulan as b on b.year = m.year and b.month = m.month
left join geser as g on g.year = m.year and g.month = m.month;`;

