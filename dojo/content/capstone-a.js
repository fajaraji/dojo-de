// Capstone A: membangun gudang data TokoKita dari awal (raw → staging → dw → mart), lengkap dengan uji kualitas,
// rekonsiliasi dengan laporan keuangan, dan dokumentasi kolom.
// Setiap langkah dijalankan di transaksi yang dibatalkan. Karena itu setup setiap soal berisi hasil rujukan semua
// langkah sebelumnya, supaya kesalahan di satu langkah tidak menular ke langkah berikutnya.

/* ---------------------------------------------------------------- langkah 1: view staging */
const STG_TX = `create schema stg;

create view stg.orders as
select order_id,
       customer_id,
       order_ts,
       order_ts::date as order_date,
       lower(trim(channel)) as channel,
       lower(trim(status)) as status,
       shipping_fee,
       updated_at
from app.orders;

create view stg.order_items as
select order_id,
       line_no,
       product_id,
       qty,
       unit_price,
       discount,
       qty * unit_price as gross_amount,
       qty * unit_price - discount as net_amount
from app.order_items;

create view stg.payments as
select payment_id,
       order_id,
       paid_ts,
       paid_ts::date as paid_date,
       lower(trim(method)) as method,
       lower(trim(status)) as status,
       amount
from app.payments;`;

const STG_CITIES = `create view stg.cities as
select city_id,
       trim(city_name) as city_name,
       trim(province) as province
from app.cities;`;

const STG_MASTER_REST = `create view stg.categories as
select category_id,
       trim(category_name) as category_name,
       parent_id
from app.categories;

create view stg.products as
select product_id,
       upper(trim(sku)) as sku,
       trim(product_name) as product_name,
       category_id,
       trim(brand) as brand,
       is_active
from app.products;

create view stg.customers as
select customer_id,
       trim(full_name) as full_name,
       city_id,
       trim(segment) as segment,
       signup_date
from app.customers;

create view stg.customer_snapshot as
select snapshot_date,
       customer_id,
       trim(full_name) as full_name,
       city_id,
       trim(segment) as segment
from raw.customer_snapshot;`;

const STG_MASTER = `${STG_CITIES}\n\n${STG_MASTER_REST}`;
const STG = `${STG_TX}\n\n${STG_MASTER}`;

/* ---------------------------------------------------------------- langkah 2: dimensi */
const DIM_DATE = `create schema dw;

create table dw.dim_date (
  date_key integer primary key,
  full_date date not null unique,
  year integer not null,
  quarter integer not null,
  month integer not null,
  month_name text not null,
  day_of_month integer not null,
  day_of_week integer not null,
  day_name text not null,
  is_weekend boolean not null
);

insert into dw.dim_date
with tanggal as (
  select g::date as d
  from generate_series(date '2024-01-01', date '2025-12-31', interval '1 day') as g
)
select to_char(d, 'YYYYMMDD')::integer, d,
       extract(year from d), extract(quarter from d), extract(month from d),
       to_char(d, 'FMMonth'), extract(day from d),
       extract(isodow from d), to_char(d, 'FMDay'),
       extract(isodow from d) in (6, 7)
from tanggal;

insert into dw.dim_date
values (-1, date '9999-12-31', 9999, 4, 12, 'Belum terjadi', 31, 5, 'Belum terjadi', false);`;

const DIM_PRODUCT = `create table dw.dim_product (
  product_sk integer generated by default as identity primary key,
  product_id integer not null unique,
  sku text not null,
  product_name text not null,
  brand text not null,
  category_name text not null,
  parent_category_name text not null,
  is_active boolean not null
);

insert into dw.dim_product (product_sk, product_id, sku, product_name, brand, category_name, parent_category_name, is_active)
values (-1, -1, 'Tidak diketahui', 'Produk tidak diketahui', 'Tidak diketahui', 'Tidak diketahui', 'Tidak diketahui', false);

insert into dw.dim_product (product_id, sku, product_name, brand, category_name, parent_category_name, is_active)
select p.product_id, p.sku, p.product_name, p.brand, c.category_name, pc.category_name, p.is_active
from stg.products as p
join stg.categories as c on c.category_id = p.category_id
join stg.categories as pc on pc.category_id = c.parent_id
order by p.product_id
on conflict (product_id) do update
set sku = excluded.sku,
    product_name = excluded.product_name,
    brand = excluded.brand,
    category_name = excluded.category_name,
    parent_category_name = excluded.parent_category_name,
    is_active = excluded.is_active;`;

const DIM_CUSTOMER = `create table dw.dim_customer (
  customer_sk integer generated always as identity primary key,
  customer_id integer not null,
  full_name text not null,
  city_id integer not null,
  city_name text not null,
  segment text not null,
  valid_from date not null,
  valid_to date not null,
  is_current boolean not null
);

insert into dw.dim_customer (customer_sk, customer_id, full_name, city_id, city_name, segment, valid_from, valid_to, is_current)
overriding system value
values (-1, -1, 'Pelanggan tidak diketahui', -1, 'Tidak diketahui', 'Tidak diketahui', date '1900-01-01', date '9999-12-31', true);

insert into dw.dim_customer (customer_id, full_name, city_id, city_name, segment, valid_from, valid_to, is_current)
with potret as (
  select snapshot_date, customer_id, full_name, city_id, segment,
         lag(city_id) over (partition by customer_id order by snapshot_date) as kota_sebelumnya,
         lag(segment) over (partition by customer_id order by snapshot_date) as segmen_sebelumnya
  from stg.customer_snapshot
),
awal_versi as (
  select snapshot_date, customer_id, full_name, city_id, segment
  from potret
  where kota_sebelumnya is null
     or city_id <> kota_sebelumnya
     or segment <> segmen_sebelumnya
),
versi as (
  select a.*,
         row_number() over (partition by customer_id order by snapshot_date) as nomor_versi,
         lead(snapshot_date) over (partition by customer_id order by snapshot_date) as awal_berikutnya
  from awal_versi as a
)
select v.customer_id, v.full_name, v.city_id, ci.city_name, v.segment,
       case when v.nomor_versi = 1 then cu.signup_date else v.snapshot_date end,
       coalesce(v.awal_berikutnya - 1, date '9999-12-31'),
       v.awal_berikutnya is null
from versi as v
join stg.cities as ci on ci.city_id = v.city_id
join stg.customers as cu on cu.customer_id = v.customer_id
order by v.customer_id, v.snapshot_date;`;

const DIMS = `${DIM_DATE}\n\n${DIM_PRODUCT}\n\n${DIM_CUSTOMER}`;

/* ---------------------------------------------------------------- langkah 3: fakta */
const FACT_ORDER_LINE = `create table dw.fact_order_line (
  order_id integer not null,
  line_no integer not null,
  order_date_key integer not null references dw.dim_date (date_key),
  customer_sk integer not null references dw.dim_customer (customer_sk),
  product_sk integer not null references dw.dim_product (product_sk),
  qty integer not null,
  gross_amount numeric(14,2) not null,
  discount numeric(14,2) not null,
  net_amount numeric(14,2) not null,
  primary key (order_id, line_no)
);

insert into dw.fact_order_line
  (order_id, line_no, order_date_key, customer_sk, product_sk, qty, gross_amount, discount, net_amount)
select oi.order_id, oi.line_no,
       coalesce(d.date_key, -1),
       coalesce(c.customer_sk, -1),
       coalesce(p.product_sk, -1),
       oi.qty, oi.gross_amount, oi.discount, oi.net_amount
from stg.order_items as oi
join stg.orders as o on o.order_id = oi.order_id
left join dw.dim_date as d on d.full_date = o.order_date
left join dw.dim_customer as c
  on c.customer_id = o.customer_id
 and o.order_date between c.valid_from and c.valid_to
left join dw.dim_product as p on p.product_id = oi.product_id;`;

const FACT_PAYMENT = `create table dw.fact_payment (
  payment_id integer primary key,
  order_id integer not null,
  paid_date_key integer not null references dw.dim_date (date_key),
  customer_sk integer not null references dw.dim_customer (customer_sk),
  method text not null,
  status text not null,
  amount numeric(12,2) not null
);

insert into dw.fact_payment (payment_id, order_id, paid_date_key, customer_sk, method, status, amount)
select pa.payment_id, pa.order_id,
       coalesce(d.date_key, -1),
       coalesce(c.customer_sk, -1),
       pa.method, pa.status, pa.amount
from stg.payments as pa
join stg.orders as o on o.order_id = pa.order_id
left join dw.dim_date as d on d.full_date = pa.paid_date
left join dw.dim_customer as c
  on c.customer_id = o.customer_id
 and pa.paid_date between c.valid_from and c.valid_to;`;

